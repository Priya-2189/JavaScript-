/* //Operators in JS
1.Arithmetic Operators
   +,*,-,/;
*/
let a=10;
let b=2;
console.log("a+b:",a+b);
console.log("a-b:",a-b);
console.log("a*b:",a*b);
console.log("a/b:",a/b);
console.log("a%b:",a%b);
console.log("a**b:",a**b);
//Unary Operation
//post incremnt
console.log("a++:",a++);
console.log("a++:",a);
//post decrement
console.log("a--:",a--);
console.log("a--:",a);
//pre incremnt
console.log("++a:",++a);
//pre decrement
console.log("--a:",--a);

